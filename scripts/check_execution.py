#!/usr/bin/env python3
"""
Check that every planned artifact exists in the vault, and nothing else does.

"Executed" is not a status field someone remembered to update — it is a claim
that has to hold against the vault. This checks it in both directions, because
each catches a different failure:

  forward   every planned note exists. A missing note is silent: nothing else
            reports it, and the vault still validates, indexes and retrieves.
  reverse   every note on disk is accounted for by some plan. An unplanned note
            is not automatically wrong, but it is unexplained, and an unexplained
            note in an evaluation vault is a question nobody can answer later.

    python3 scripts/check_execution.py multihop_rag --vault vaults/multihop_rag

Also verifies what only the whole vault can show: that every corpus document is
represented, and that every note is REACHABLE from the root entry point. A note
with no path from the root is retrievable by name and unreachable by traversal,
which makes it invisible to the graph arm the experiment measures.
"""

from __future__ import annotations

import argparse
import json
import sqlite3
import sys
from collections import deque
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("slug")
    ap.add_argument("--vault")
    ap.add_argument("--root", default="entry_multihop_rag.md")
    a = ap.parse_args()

    P = ROOT / "experiments" / "plans" / a.slug
    V = Path(a.vault or f"vaults/{a.slug}")
    disk = {p.name for p in V.glob("*.md")}

    planned: dict[str, str] = {}
    for f in sorted((P / "clusters").glob("c*.json")) if (P / "clusters").is_dir() else []:
        for s in json.loads(f.read_text())["subplans"]:
            for n in s["notes"]:
                planned[n["note"]] = f.stem
    for f in sorted(P.glob("subplan_*_assignments.json")):
        for n in json.loads(f.read_text()):
            planned.setdefault(n, f.stem)

    reuse = json.loads((P / "term_reuse.json").read_text()) if (P / "term_reuse.json").exists() else {}
    terms = json.loads((P / "terms.json").read_text()) if (P / "terms.json").exists() else {}
    for t in terms:
        if t not in reuse:
            planned.setdefault(f"term_{t}.md", "terms.json")
    planned.setdefault("glossary.md", "terms.json")

    bad = []
    missing = sorted(n for n in planned if n not in disk)
    for n in missing:
        bad.append(f"MISSING    {n}  (planned in {planned[n]})")

    # entry points are generated by the plan rather than listed in it
    extra = sorted(n for n in disk if n not in planned and not n.startswith("entry_"))
    for n in extra:
        bad.append(f"UNPLANNED  {n}  (on disk, in no plan)")

    print(f"planned notes   {len(planned):,}")
    print(f"vault notes     {len(disk):,}")
    print(f"entry points    {sum(1 for n in disk if n.startswith('entry_'))}")
    print(f"terms reused    {len(reuse)} (recorded in term_reuse.json)")

    db = V / "notes.db"
    if db.exists():
        con = sqlite3.connect(db)
        idx = json.loads((ROOT / "data" / "corpus" / a.slug / "index.json").read_text())
        cited: set[str] = set()
        for (s,) in con.execute("SELECT source_doc FROM notes"):
            cited |= {x.strip() for x in (s or "").split(",") if x.strip()}
        uncited = sorted(set(idx) - cited)
        print(f"corpus coverage {len(set(idx) & cited)}/{len(idx)} documents cited")
        for d in uncited:
            bad.append(f"UNCITED    {d}  (no note draws on this document)")

        adj: dict[str, list[str]] = {}
        for s, t in con.execute(
                "SELECT source_note_id, target_note_id FROM note_links WHERE resolved=1"):
            adj.setdefault(s, []).append(t)
        alln = {r[0] for r in con.execute("SELECT note_id FROM notes")}
        con.close()
        if a.root in alln:
            seen = {a.root}
            q = deque([a.root])
            while q:
                for t in adj.get(q.popleft(), ()):
                    if t not in seen:
                        seen.add(t)
                        q.append(t)
            print(f"reachable       {len(seen):,}/{len(alln):,} from {a.root}")
            for n in sorted(alln - seen)[:20]:
                bad.append(f"UNREACHABLE {n}  (no path from the root entry point)")
        else:
            bad.append(f"NO-ROOT    {a.root} is not in the vault")

    if bad:
        print(f"\nFAIL — {len(bad)} finding(s):")
        for b in bad[:40]:
            print("  " + b)
        if len(bad) > 40:
            print(f"  ... and {len(bad) - 40} more")
        sys.exit(1)
    print("\nPASS — every plan executed, every note accounted for, "
          "every document cited, every note reachable")


if __name__ == "__main__":
    main()
